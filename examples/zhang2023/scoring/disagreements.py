#!/usr/bin/env python3
# Copied from the paper's experiment (demo_v2/ground_truth/disagreements.py) as a worked example. Only the
# path set-up changed: set ZHANG_DEMO_ROOT to the experiment folder. Outputs are written there.
"""
Codebook-stage disagreements with Zhang et al. for the Full candidate codebook (defensible mapping,
whole-thread labels, evaluation threads): council assignments on threads that Zhang et al. labeled for the
same question, where the code maps to none of the categories they gave the thread. Grouped by question,
council code and Zhang et al.'s category. Writes disagreements_full.json.
  python3 disagreements.py
"""
import json
from collections import Counter, defaultdict
from pathlib import Path
import os
ROOT = Path(os.environ["ZHANG_DEMO_ROOT"]).resolve()
HERE = ROOT / "ground_truth"
RUNS = HERE.parent / "runs"
DIM = {"RQ1.4": "FU", "RQ1.5": "PU", "RQ2.1": "BE", "RQ2.2": "LC", "RQ2.3": "EF"}
import csv
ev = set(json.loads((HERE.parent / "data/splits.json").read_text())["evaluation"])
cats = json.loads((HERE / "zhang_codebook_v2.json").read_text())["categories"]
zc = {c["name"].strip().lower(): c["id"] for c in cats}
zname = {c["id"]: c["name"] for c in cats}
lab = defaultdict(set)
for r in csv.DictReader((HERE / "human_labels.csv").open()):
    if r["uid"] in ev and r["n_candidate_posts"] == "1":
        lab[r["uid"]].add(zc[r["category"].strip().lower().replace("  ", " ")])
book = json.loads((RUNS / "full/codebooks/candidate_codebook.json").read_text())["codes"]
mp = {m["code_id"]: {c["id"] for c in m["categories"]} for m in json.loads((HERE / "mapping_def_full.json").read_text())["mapping"]}
cname = {c["id"]: c.get("name") or c.get("label") or c["id"] for c in book}
rq = {c["id"]: c.get("rq", "") for c in book}
n_sq = n_ag = 0
dis = Counter()
for c in book:
    for u in c["units"]:
        if u not in ev or not mp.get(c["id"]):
            continue
        same = {x for x in lab.get(u, ()) if x[:2] == DIM.get(rq[c["id"]])}
        if not same:
            continue
        n_sq += 1
        if mp[c["id"]] & lab[u]:
            n_ag += 1
        else:
            dis[(rq[c["id"]], cname[c["id"]], " / ".join(sorted(zname[x] for x in same)),
                 " / ".join(sorted(zname[x] for x in mp[c["id"]])))] += 1
assert n_sq - n_ag == sum(dis.values())
out = [{"rq": q, "council_code": cc, "zhang_category": zcat, "code_maps_to": m, "threads": n}
       for (q, cc, zcat, m), n in sorted(dis.items(), key=lambda kv: (kv[0][0], -kv[1], kv[0][1]))]
(HERE / "disagreements_full.json").write_text(json.dumps({"pairs": n_sq, "agreeing": n_ag, "disagreeing": n_sq - n_ag, "rows": out}, indent=1))
print(n_sq, n_ag, n_sq - n_ag, len(out))
for q in DIM:
    print(q, sum(r["threads"] for r in out if r["rq"] == q))

# supplement table (Appendix F.3)
QN = {"RQ1.4": "Functions", "RQ1.5": "Purposes", "RQ2.1": "Benefits", "RQ2.2": "Limitations and challenges", "RQ2.3": "Expected features"}
esc = lambda s: s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")
hdr = r"\textbf{Council code} & \textbf{Code maps to} & \textbf{Zhang et al.\ category} & \textbf{n} \\"
L = ["% GENERATED by demo_v2/ground_truth/disagreements.py. Do not edit by hand.", r"{\footnotesize", r"\setlength{\tabcolsep}{3pt}",
     r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{\linewidth-9.6cm}>{\raggedright\arraybackslash}p{4.4cm}>{\raggedright\arraybackslash}p{3.8cm}r@{}}",
     rf"\caption{{The {n_sq - n_ag} assignments that count against the precision of the \full{{}} codebook, by research question, council code and the category Zhang et al.~\cite{{zhang2023demystifying}} gave the thread. ``Code maps to'': the categories the council code maps to (Appendix~\ref{{app:experiment}}, F.2). n: evaluation threads.}}\label{{tab:f-disagree}}\\",
     r"\toprule", hdr, r"\midrule", r"\endfirsthead",
     r"\multicolumn{4}{@{}l}{\itshape Table~\ref{tab:f-disagree}, continued}\\", r"\toprule", hdr, r"\midrule", r"\endhead",
     r"\midrule\multicolumn{4}{r@{}}{\itshape continued on next page}\\", r"\endfoot", r"\bottomrule", r"\endlastfoot"]
for q in DIM:
    rs = [r for r in out if r["rq"] == q]
    L.append(rf"\multicolumn{{4}}{{@{{}}l}}{{\textit{{{QN[q]}}} ({sum(r['threads'] for r in rs)})}}\\")
    for r in rs:
        L.append(f"{esc(r['council_code'])} & {esc(r['code_maps_to']).replace(' / ', '; ')} & {esc(r['zhang_category']).replace(' / ', '; ')} & {r['threads']} \\\\")
    if q != "RQ2.3":
        L.append(r"\addlinespace")
L += [r"\end{longtable}", "}"]
(HERE / "appendix_F_disagreements.tex").write_text("\n".join(L) + "\n")
